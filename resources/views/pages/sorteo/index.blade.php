  <h1>BASES LEGALES DEL SORTEO DE 10 VUELOS POR LA COMPRA DE LENTILLAS DIARIAS</h1>

  <p><strong>UNIÓN GENERAL DE OPTICAS, S.L.</strong>, con CIF B50806629 y domicilio social en Calle de la Variant, 21, Torrefarrera – 25123, convoca una promoción para los centros adheridos en ella en España y Canarias.</p>

  <p><span class="clausula">PRIMERA. -</span>  El objetivo de la promoción es sortear 10 VUELOS DE IDA Y VUELTA PARA DOS PERSONAS A CIENTOS DE DESTINOS A ESCOGER ENTRE ESPAÑA, EUROPA Y MARRUECOS entre todos los usuarios que hayan comprado lentillas diarias en los centros UGO adheridos a la promoción. </p>

  <p><span class="clausula">SEGUNDA. -</span> La promoción se llevará a cabo desde las 12:00 horas del 30/04/2025 hasta las 23.59 horas del 30/06/2025 (“Periodo Promocional”).</p>

  <p><span class="clausula">TERCERA. -</span>  Podrán participar en el sorteo todas aquellas personas físicas, mayores de edad que residan en el estado español y/o en Canarias.</p>

  <p><span class="clausula">CUARTA. -</span>  El premio para cada uno de los 10 ganadores consiste en 1 VUELO PARA DOS PERSONAS DE IDA Y VUELTA A CIENTOS DE DESTINOS A ESCOGER ENTRE ESPAÑA, EUROPA Y MARRUECOS. Se sacarán 12 nombres de los usuarios que hayan participado en el sorteo de los centros asociados a UGO (Unión General de Ópticas) a nivel nacional y de Canarias.</p>

  <p><span class="clausula">QUINTA. -</span> El periodo promocional finalizará a las 23.59 horas del 30/06/2025. UNION GENERAL DE OPTICAS procederá a realizar el sorteo a las 12:00 HORAS DEL DÍA 01/07/2025 para conocer a los 10 ganadores y a los suplentes correspondientes a través de la aplicación Easypromos.</p>

  <p><span class="clausula">SEXTA. -</span>  En el caso de que no se localice a alguno de los 10 ganadores en un plazo de 48 horas desde el anuncio de este, o alguno de estos renuncie al premio o no cumpla los requisitos establecidos en estas Bases, UNION GENERAL DE OPTICAS se reserva el derecho a proceder a la entrega del premio al suplente. En caso de ocurrir la misma circunstancia, el premio se declarará desierto.</p>

